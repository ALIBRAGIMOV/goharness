func TestPolicyFileEditIsRejected(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", cleanLibrary)
	f.write("lib/lib_test.go", cleanLibraryTest)
	f.commit("clean baseline")
	f.write("goharness.yaml", "# scoped exceptions live here\n")

	result := run(t, f, verify.ModeVerify)
	requireVerdict(t, result, admission.VerdictRejected)
	if !slices.Contains(blockingRules(result.Evidence), policy.RulePolicyEdit) {
		t.Fatalf("blocking rules = %v, want %s", blockingRules(result.Evidence), policy.RulePolicyEdit)
	}
}

// TestPolicyFileEditIsAllowedWhenTheBaseContractDeclaresIt pins the only route
// to a policy edit: the grant must already be committed at the base revision,
// where the change under verification could not have written it.
func TestPolicyFileEditIsAllowedWhenTheBaseContractDeclaresIt(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", cleanLibrary)
	f.write("lib/lib_test.go", cleanLibraryTest)
	f.write("goharness.task.yaml", "goal: reviewed policy update\nallowPolicyEdit: true\n")
	f.commit("baseline carrying a reviewed contract")
	f.write("lib/lib.go", renamedAnswerLibrary)
	f.commit("the change the contract authorises")
	f.write("goharness.yaml", "# scoped exceptions live here\n")

	result := run(t, f, verify.ModeVerify)
	requireVerdict(t, result, admission.VerdictAdmitted)
	if !result.Contract.Authenticated {
		t.Fatalf("contract from %s was not authenticated", result.Contract.Source)
	}
	if slices.Contains(ruleIDs(result.Evidence), policy.RulePolicyEdit) {
		t.Fatalf("allowPolicyEdit was ignored: %v", ruleIDs(result.Evidence))
	}
}

func TestGeneratedFileEditIsAdvisoryEvidence(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", cleanLibrary)
	f.write("lib/lib_test.go", cleanLibraryTest)
	f.write("lib/generated.go", generatedFixture)
	f.commit("baseline with generated code")
	f.write("lib/generated.go", "// Code generated by fixturegen. DO NOT EDIT.\n\npackage lib\n\n// Generated returns a fixed value.\nfunc Generated() int {\n\treturn 8\n}\n")

	result := run(t, f, verify.ModeVerify)
	requireVerdict(t, result, admission.VerdictAdmitted)
	if !slices.Contains(ruleIDs(result.Evidence), policy.RuleGeneratedEdit) {
		t.Fatalf("hand-edited generated file was not flagged: %v", ruleIDs(result.Evidence))
	}
	if slices.Contains(blockingRules(result.Evidence), policy.RuleGeneratedEdit) {
		t.Fatalf("%s must stay advisory", policy.RuleGeneratedEdit)
	}
}

func TestLeakedGoroutineRejectsTheChange(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", cleanLibrary)
	f.write("lib/lib_test.go", cleanLibraryTest)
	f.commit("clean baseline")
	f.write("worker/worker.go", leakyWorker)
	f.write("worker/worker_test.go", leakingWorkerTest)

	result := run(t, f, verify.ModeVerify)
	requireVerdict(t, result, admission.VerdictRejected)
	if !slices.Contains(blockingRules(result.Evidence), policy.RuleGoroutineLeak) {
		t.Fatalf("blocking rules = %v, want %s", blockingRules(result.Evidence), policy.RuleGoroutineLeak)
	}
	// A leak belongs to a package rather than to a line, but a finding with no
	// location at all is one a reader cannot open and a scoped exception cannot
	// reach. The package directory is the most precise anchor that is true.
	for _, e := range result.Evidence {
		if e.RuleID != policy.RuleGoroutineLeak {
			continue
		}
		if e.File == "" {
			t.Fatalf("a leak finding carried no location: %+v", e)
		}
		if filepath.IsAbs(e.File) {
			t.Fatalf("a leak finding was anchored outside the module: %q", e.File)
		}
	}
}

func TestExistingTestMainMakesLeakEvidenceUnproducible(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", cleanLibrary)
	f.write("lib/lib_test.go", cleanLibraryTest)
	f.commit("clean baseline")
	f.write("worker/worker.go", leakyWorker)
	f.write("worker/worker_test.go", stoppedWorkerTest)

	result := run(t, f, verify.ModeVerify)
	requireVerdict(t, result, admission.VerdictInconclusive)
	if !slices.ContainsFunc(result.Unproducible, func(u admission.Unproducible) bool {
		return u.Kind == admission.KindLeakClean
	}) {
		t.Fatalf("expected %s to be unproducible, got %v", admission.KindLeakClean, result.Unproducible)
	}
	// The same fact, reachable as data rather than only as prose inside a reason.
	// A consumer deciding where the run is blind cannot parse an English sentence
	// for it, and a coverage statement nobody can read is not one.
	if !slices.ContainsFunc(result.LeakBlockedPackages, func(pkg string) bool {
		return strings.HasSuffix(pkg, "/worker")
	}) {
		t.Fatalf("the blocked package is not in coverage: %v", result.LeakBlockedPackages)
	}
	if len(result.Execution.Packages) == 0 || len(result.Execution.Files) == 0 {
		t.Fatalf("coverage reports nothing judged: %+v", result.Execution)
	}
}
