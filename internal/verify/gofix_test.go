// Fixture sources for the //go:fix inline mechanism: a library that marks a
// deprecated function for automatic migration, and a consumer that has not
// migrated yet.
const (
	inlineLibrary = `package lib

// Pow returns base raised to exp.
func Pow(base, exp int) int {
	result := 1
	for range exp {
		result *= base
	}
	return result
}

// Square returns x squared.
//
// Deprecated: call Pow directly.
//go:fix inline
func Square(x int) int { return Pow(x, 2) }
`

	inlineLibraryTest = `package lib

import "testing"

func TestPow(t *testing.T) {
	if got := Pow(3, 2); got != 9 {
		t.Fatalf("Pow(3, 2) = %d, want 9", got)
	}
}
`

	migratedConsumer = `package consumer

import "example.com/fixture/lib"

// Nine returns three squared.
func Nine() int {
	return lib.Pow(3, 2)
}
`

	unmigratedConsumer = `package consumer

import "example.com/fixture/lib"

// Nine returns three squared.
func Nine() int {
	return lib.Square(3)
}
`

	generatedUnmigratedConsumer = `// Code generated by fixture. DO NOT EDIT.

package consumer

import "example.com/fixture/lib"

// Four returns two squared.
func Four() int {
	return lib.Square(2)
}
`

	consumerNineTest = `package consumer

import "testing"

func TestNine(t *testing.T) {
	if got := Nine(); got != 9 {
		t.Fatalf("Nine() = %d, want 9", got)
	}
}
`
)

// TestGoFixAnalyzerSetMatchesTheInstalledToolchain keeps the checked-in
// analyzer set total against the toolchain. An analyzer the policy enables and
// the toolchain dropped would fail as an undefined flag mid-run; one the
// toolchain added and the policy never classified would sit unrun and unnoticed
// until someone read the release notes.
func TestGoFixAnalyzerSetMatchesTheInstalledToolchain(t *testing.T) {
	support, err := tool.InspectFixAnalyzers(t.Context(), tool.ExecRunner{}, moduleRoot(t),
		policy.GoFixAnalyzers(), policy.GoFixKnownAnalyzers())
	if err != nil {
		t.Fatalf("InspectFixAnalyzers: %v", err)
	}
	if len(support.Missing) > 0 {
		t.Fatalf("%s does not register the enabled analyzer(s) %v", tool.GoVersion(), support.Missing)
	}
	if len(support.Unregistered) > 0 {
		t.Fatalf("%s registers the analyzer(s) %v that internal/policy/rules_gofix.go does not classify; "+
			"add each one with a rationale, or record why it stays off",
			tool.GoVersion(), support.Unregistered)
	}
}

// TestGoFixReportsUnmigratedCallWithItsCommand is the end-to-end case for the
// consumer side of //go:fix inline: a call the author marked for automatic
// migration is reported, it carries the command that performs the migration,
// and the tree is untouched by the run that found it.
func TestGoFixReportsUnmigratedCallWithItsCommand(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", inlineLibrary)
	f.write("lib/lib_test.go", inlineLibraryTest)
	f.write("consumer/consumer.go", migratedConsumer)
	f.write("consumer/consumer_test.go", consumerNineTest)
	f.commit("library marks Square for inlining, consumer already migrated")

	f.write("consumer/consumer.go", unmigratedConsumer)
	f.commit("consumer calls the deprecated spelling")
	before := f.porcelain()

	result := run(t, f, verify.ModeVerify)
	found := findingsFor(result.Evidence, policy.GoFixRuleID("inline"))
	if len(found) == 0 {
		t.Fatalf("no %s evidence; rules = %v, failures = %+v",
			policy.GoFixRuleID("inline"), ruleIDs(result.Evidence), result.Failures)
	}
	got := found[0]
	if got.State != evidence.StateNew {
		t.Fatalf("state = %q, want the call the change introduced to be new", got.State)
	}
	if got.Fix == nil || !strings.HasPrefix(got.Fix.Command, "go fix -inline ./consumer") {
		t.Fatalf("fix = %+v, want the narrowest command that closes it", got.Fix)
	}
	if got.Classification != evidence.ClassificationAdvisory {
		t.Fatalf("classification = %q; go fix rules enter advisory", got.Classification)
	}
	if after := f.porcelain(); after != before {
		t.Fatalf("the run changed the worktree:\nbefore %q\nafter %q", before, after)
	}
}

// TestGoFixStaysSilentOnCodeItHasNothingToSay keeps the check honest in the
// other direction: a rule that reports on healthy code is worse than no rule.
func TestGoFixStaysSilentOnCodeItHasNothingToSay(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", cleanLibrary)
	f.write("lib/lib_test.go", cleanLibraryTest)
	f.commit("clean baseline")
	f.write("consumer/consumer.go", consumerLibrary)
	f.write("consumer/consumer_test.go", consumerTest)

	result := run(t, f, verify.ModeVerify)
	requireVerdict(t, result, admission.VerdictAdmitted)
	for _, e := range result.Evidence {
		if strings.HasPrefix(e.RuleID, policy.GoFixRulePrefix) {
			t.Fatalf("go fix reported %s on clean code: %s", e.RuleID, e.Message)
		}
	}
}

// TestGoFixIgnoresDiagnosticsItCannotFix records a deliberate limit, so that
// the day it stops holding a test says so.
//
// The inliner refuses to rewrite generated files and reports that refusal as a
// diagnostic with no edit. The harness drops it: what makes this suite precise
// enough to report is the edit, and a fix-less diagnostic carries none. The
// consequence is that a `Code generated` header hides go fix findings in a file
// its author wrote. Nothing can be admitted through that gap while every
// GO-FIX rule is advisory, and closing it is part of promoting the first one to
// required.
func TestGoFixIgnoresDiagnosticsItCannotFix(t *testing.T) {
	useGolangci(t)
	f := newFixture(t)
	f.write("lib/lib.go", inlineLibrary)
	f.write("lib/lib_test.go", inlineLibraryTest)
	f.write("consumer/consumer.go", migratedConsumer)
	f.write("consumer/consumer_test.go", consumerNineTest)
	f.commit("library marks Square for inlining, consumer already migrated")

	f.write("consumer/generated.go", generatedUnmigratedConsumer)
	f.commit("a generated file calls the deprecated spelling")

	result := run(t, f, verify.ModeVerify)
	for _, e := range findingsFor(result.Evidence, policy.GoFixRuleID("inline")) {
		if e.File == "consumer/generated.go" {
			t.Fatalf("a fix-less diagnostic became evidence: %s", e.Message)
		}
	}
}

func findingsFor(items []evidence.Evidence, ruleID string) []evidence.Evidence {
	return slices.DeleteFunc(slices.Clone(items), func(e evidence.Evidence) bool {
		return e.RuleID != ruleID
	})
}
